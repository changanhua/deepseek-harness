import { build } from 'esbuild'
import { mkdir, readFile, realpath } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const extensionRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const workspaceRoot = resolve(extensionRoot, '../..')
const outfile = resolve(extensionRoot, 'vendor/puppeteer.js')
const extensionTransportPath = await realpath(resolve(workspaceRoot, 'node_modules/puppeteer-core/lib/esm/puppeteer/cdp/ExtensionTransport.js'))
const detachedWithoutPromise = 'void chrome.debugger.detach({ tabId: this.#tabId });'
const detachedWithPromise = 'return chrome.debugger.detach({ tabId: this.#tabId });'

await mkdir(dirname(outfile), { recursive: true })
await build({
  entryPoints: [resolve(extensionRoot, 'scripts/puppeteer-entry.js')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome116',
  alias: {
    // `puppeteer.connect({ transport })` reaches the CDP path. The optional
    // WebDriver BiDi implementation imports Node-only chromium-bidi code at
    // module evaluation time, so an extension bundle replaces that unused
    // branch with the two declarations its dormant classes require.
    'chromium-bidi/lib/cjs/bidiMapper/BidiMapper.js': resolve(extensionRoot, 'scripts/bidi-unavailable.js'),
  },
  plugins: [{
    name: 'awaitable-extension-transport-detach',
    setup(build) {
      build.onLoad({ filter: /ExtensionTransport\.js$/ }, async args => {
        if (args.path !== extensionTransportPath) return
        const source = await readFile(args.path, 'utf8')
        const occurrences = source.split(detachedWithoutPromise).length - 1
        if (occurrences !== 1) throw new Error(`expected one ExtensionTransport detach call, found ${occurrences}`)
        return { contents: source.replace(detachedWithoutPromise, detachedWithPromise), loader: 'js' }
      })
    },
  }],
  legalComments: 'linked',
  banner: {
    js: '/* Generated by pnpm run build:chrome-extension. Do not edit. */',
  },
})
